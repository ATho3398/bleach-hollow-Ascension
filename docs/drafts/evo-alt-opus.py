def rows_for(faction, data):
    gmap = SG if faction == '사신' else HG
    lib_name = '만해' if faction == '사신' else '레스렉시온'
    out = []
    for c in COMMON:
        out.append([c[0], c[1], c[2][faction], c[3], c[4], c[5], c[6], c[7], c[8]])
    for e in data:
        st = '4(히든)' if e['hidden'] else '4'
        out.append([st, e['fid'], e['name'], gmap[e['g']], e['trait'], e['ua'], e['blk'], '—', e['intent']])
        out.append([f'5(해방·{lib_name})', e['fid'], e['name'], gmap[e['g']], KEEP, e['lib_ua'], e['lib_blk'], e['mode'],
                    f'해방 {e["mode"]}'])
    return out


