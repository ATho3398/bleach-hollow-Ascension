def write_xlsx():
    wb = Workbook()
    bold = Font(bold=True)
    head_fill = PatternFill('solid', fgColor='DDDDDD')
    lib_fill = PatternFill('solid', fgColor='E8F0FF')
    memo_fill = PatternFill('solid', fgColor='FFF7CC')
    widths = [14, 22, 30, 14, 24, 56, 48, 10, 34, 28]
    first = True
    for fac, data in (('사신', SHINIGAMI), ('호로', HOLLOW)):
        ws = wb.active if first else wb.create_sheet()
        first = False
        ws.title = fac
        ws.append([f'{fac} — opus 비교안 · 파란 줄 = 5단계(해방, 레스렉시온/만해 때만) · 특성은 해방해도 그대로 · '
                   '화상 = 걸린 적을 때리면 추가 피해 · 독 = 지속 피해 · 수치 전부 provisional'])
        ws['A1'].font = bold
        ws.append(HEAD + ['사용자 메모'])
        for r in rows_for(fac, data):
            ws.append(r + [''])
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
        for c in ws[2]:
            c.font = bold
            c.fill = head_fill
            c.alignment = Alignment(wrap_text=True, vertical='center')
        for row in ws.iter_rows(min_row=3):
            for c in row:
                c.alignment = Alignment(wrap_text=True, vertical='top')
            if str(row[0].value).startswith('5'):
                for c in row[:-1]:
                    c.fill = lib_fill
            row[-1].fill = memo_fill
        ws.freeze_panes = 'D3'
        ws.auto_filter.ref = f'A2:J{ws.max_row}'
    ws = wb.create_sheet('설계 방침')
    ws.append(['항목', '내용'])
    for p in PRINCIPLES:
        ws.append(list(p))
    ws.column_dimensions['A'].width = 20
    ws.column_dimensions['B'].width = 120
    for c in ws[1]:
        c.font = bold
        c.fill = head_fill
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
    wb.save(XLSX)


