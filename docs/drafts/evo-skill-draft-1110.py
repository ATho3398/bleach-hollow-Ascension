def check():
    import json
    forms = os.path.join(HERE, '..', '..', 'src', 'data', 'evolution', 'forms.json')
    ids = {f['id'] for f in json.load(open(forms, encoding='utf-8'))}
    for name, rows in FACTIONS:
        got = [r[1] for r in rows]
        assert set(got) == ids and len(got) == len(ids), (name, ids ^ set(got))
        for r in rows:
            assert len(r) == len(HEAD) - 1, r[1]   # 기본 행은 '변화 방식' 열 없이 11열
            st = r[0]
            if st == '2':
                assert r[4] == NONE and r[6] == '—', r[1]
            elif st.startswith('3'):
                assert r[4] != NONE and r[6] == '—', r[1]   # 3단계 = 특성만
            else:
                assert r[4] != NONE and r[6] != '—', r[1]   # 4단계 = 특성 + 특수 블록
    # 같은 자리 두 종족이 겹치지 않는지(공통 고정 이름 제외)
    fixed = {NONE, '—'} | {v[0] for v in COMMON_T3.values()}
    for s_, h_ in zip(SHINIGAMI, HOLLOW):
        if s_[0].startswith('3'):
            assert s_[4:] == h_[4:], s_[1]   # 3단계 두 종족 공통
    for s, h in zip(SHINIGAMI, HOLLOW):
        assert s[1] == h[1], s[1]
        if s[4] not in fixed:
            assert s[4] != h[4], s[1]
        if s[6] not in fixed:
            assert s[6] != h[6], s[1]
    # 한 종족 안 이름 중복 없음
    for name, rows in FACTIONS:
        tn = [r[4] for r in rows if r[4] not in fixed]
        bn = [r[6] for r in rows if r[6] not in fixed]
        assert len(tn) == len(set(tn)), (name, '특성 이름 중복')
        assert len(bn) == len(set(bn)), (name, '블록 이름 중복')
    # v4: 4단계 진화체마다 5단계(해방) 행이 있고, 해방 표에 4단계 아닌 id 가 없음
    for name, rows in FACTIONS:
        t4ids = {r[1] for r in rows if r[0].startswith('4')}
        assert set(LIBS[name]) == t4ids, (name, set(LIBS[name]) ^ t4ids)
        for k, v in LIBS[name].items():
            assert len(v) == 8 and v[0] in (UP, CH), (name, k)
            if v[0] == CH:
                assert v[1] and v[3], (name, k, '변경은 새 이름')
        ex = expanded(name, rows)
        assert sum(1 for r in ex if r[0].startswith('5')) == len(t4ids)
        assert all(len(r) == len(HEAD) for r in ex)
        allt = [r[5] for r in ex if r[5] not in fixed]
        allb = [r[7] for r in ex if r[7] not in fixed]
        assert len(allt) == len(set(allt)), (name, '해방 포함 특성 이름 중복')
        assert len(allb) == len(set(allb)), (name, '해방 포함 블록 이름 중복')
    for k in SHINIGAMI_LIB:
        s, h = SHINIGAMI_LIB[k], HOLLOW_LIB[k]
        if s[0] == CH and h[0] == CH:
            assert s[1] != h[1] and s[3] != h[3], k


