def style(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for c in ws[1]:
        c.font = Font(bold=True); c.fill = PatternFill('solid', fgColor='DDDDDD')
    for row in ws.iter_rows():
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
    ws.freeze_panes = 'D2'

def main():
    wb = Workbook(); first = True
    for fac in ('사신', '호로'):
        ws = wb.active if first else wb.create_sheet(); first = False
        ws.title = fac
        ws.append(HEAD)
        for r in rows_for(fac):
            ws.append(r)
        style(ws, [12, 22, 28, 12, 28, 52, 46, 54, 30, 20])
        ws.auto_filter.ref = f'A1:{get_column_letter(len(HEAD))}{ws.max_row}'
    ws = wb.create_sheet('설계 방침')
    ws.append(['설계 방침 (sonnet 안)'])
    for p in POLICY:
        ws.append([p])
    ws.column_dimensions['A'].width = 140
    for row in ws.iter_rows():
        for c in row: c.alignment = Alignment(wrap_text=True, vertical='top')
    wb.save(XLSX)
