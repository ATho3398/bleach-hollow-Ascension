def rows_for(fac):
    out = []
    for i, (fid, ns, nh, kind) in enumerate(FORMS):
        name = ns if fac == '사신' else nh
        trait, ua, blk, mode, lua, lblk, intent = DATA[fac][fid]
        stage = '4(히든)' if fid.startswith('h4') else '4'
        ua_s = f'{ua[0]} — {ua[1]}'
        blk_s = blk if isinstance(blk, str) else f'{blk[0]} — {blk[1]}'
        out.append([stage, fid, name, kind, trait, ua_s, blk_s, '', intent, ''])
        lua_s = f'{mode}: {lua[0]} — {lua[1]}' + (f' / {lblk}' if lblk else '')
        lib_blk = '해방 중에만 쓰는 블록 없음' if blk_s.startswith('없음') else '4단계 특수 블록 유지(해방이 풀리면 해방 전용 블록은 바에서 사라짐)'
        out.append([stage.replace('4', '5', 1) + LIB[fac], fid, name, kind, '(그대로 — 특성은 해방해도 안 바뀜)', lua_s, lib_blk, mode, '', ''])
    return out

