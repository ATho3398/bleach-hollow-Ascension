def rows_of(name, forms):
    out = [['2', 't2:base', T2_NAME[name], C, '없음', '없음', '없음', '—', '2단계는 능력 없음(확정)', '']]
    for (stage, fid, trait), nm in zip(T3, T3_NAMES[name]):
        out.append([stage, fid, nm, C, '(3단계 공통 특성) ' + trait, '없음', '없음', '—', '두 종족 공통 — 지금 게임 값 그대로, 이 초안이 정하는 것 없음', ''])
    for f in forms:
        out.append([f['stage'], f['id'], f['name'], f['kind'], f['trait'], f['ua'], f['blk'], '—', f['intent'], ''])
        out.append(['5(해방)', f['id'], f['name'].replace(' 〔임시〕', '') + ' — ' + LIB[name], f['kind'], '(그대로 — 특성은 해방해도 안 바뀜)',
                    f['lua'], f['lblk'], f['mode'], f['lintent'], ''])
    return out


def check():
    ids = None
    for name, forms in FACTIONS:
        assert len(forms) == 28, (name, len(forms))
        cur = [f['id'] for f in forms]
        assert len(set(cur)) == 28
        if ids is None:
            ids = cur
        assert cur == ids, '두 종족 진화체 자리(ID)가 같아야 한다'
        for f in forms:
            assert f['mode'] in (UP, CH)
            for k in ('trait', 'ua', 'blk', 'lua', 'lblk', 'intent', 'lintent'):
                assert f[k], (f['id'], k)
                assert '안정도' not in f[k], (f['id'], k)
    sh = {f['id']: f for f in SHINIGAMI}
    for f in HOLLOW:   # 사신·호로 능력은 따로
        assert f['ua'] != sh[f['id']]['ua'], f['id']
    assert sh['t4:normal:physical']['blk'].startswith('없음')


def stats(forms):
    n = lambda pred: sum(1 for f in forms if pred(f))
    return dict(total=len(forms), noblock=n(lambda f: f['blk'].startswith('없음')), up=n(lambda f: f['mode'] == UP),
                ch=n(lambda f: f['mode'] == CH), p=n(lambda f: f['kind'] == P), h=n(lambda f: f['kind'] == H), b=n(lambda f: f['kind'] == B))


def write_xlsx():
    wb = Workbook()
    wb.remove(wb.active)
    head_fill = PatternFill('solid', fgColor='1F2937')
    lib_fill = PatternFill('solid', fgColor='FFF4E0')
    low_fill = PatternFill('solid', fgColor='EEEEEE')
    tmp_fill = PatternFill('solid', fgColor='FDE2E2')
    memo_fill = PatternFill('solid', fgColor='FFFBCC')
    widths = [9, 22, 30, 11, 26, 62, 58, 11, 42, 30]
    for name, forms in FACTIONS:
        ws = wb.create_sheet(name)
        ws.append(HEAD)
        for r in rows_of(name, forms):
            ws.append(r)
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
        for c in ws[1]:
            c.font = Font(bold=True, color='FFFFFF')
            c.fill = head_fill
            c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        for row in ws.iter_rows(min_row=2):
            stage = str(row[0].value)
            fill = None
            if '임시' in str(row[2].value) or '임시' in str(row[5].value):
                fill = tmp_fill
            elif stage.startswith('5'):
                fill = lib_fill
            elif stage[0] in '23':
                fill = low_fill
            for c in row:
                c.alignment = Alignment(vertical='top', wrap_text=True)
                if fill:
                    c.fill = fill
            row[-1].fill = memo_fill
            if stage.startswith('4'):
                row[2].font = Font(bold=True)
        ws.freeze_panes = 'D2'
        ws.auto_filter.ref = ws.dimensions
    ws = wb.create_sheet('설계 방침')
    ws.append(['이 초안(fable)의 특징', '내용'])
    for k, v in POLICY:
        ws.append([k, v])
    ws.append([])
    ws.append(['집계', ''])
    for name, forms in FACTIONS:
        s = stats(forms)
        ws.append([name, '4단계 진화체 %d개(평타 위주 %d · 혼합 %d · 블록 위주 %d) / 특수 블록 없는 몸 %d개 / 해방: 강화 %d · 변경 %d'
                   % (s['total'], s['p'], s['h'], s['b'], s['noblock'], s['up'], s['ch'])])
    ws.append(['색', '흰색 = 4단계 / 연주황 = 5단계(해방) / 회색 = 2·3단계(공통) / 연빨강 = 임시(실패형) / 노랑 = 사용자 메모 칸'])
    ws.column_dimensions['A'].width = 30
    ws.column_dimensions['B'].width = 130
    for c in ws[1]:
        c.font = Font(bold=True, color='FFFFFF')
        c.fill = head_fill
    for row in ws.iter_rows(min_row=2):
        row[0].font = Font(bold=True)
        for c in row:
            c.alignment = Alignment(vertical='top', wrap_text=True)
    wb.save(XLSX)


def esc(s):
    return str(s).replace('|', '/').replace('\n', ' ')


